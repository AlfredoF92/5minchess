const dict = { it, en };
let lang = "en";

try {
  if (window.CHESS_LANG === "it" || window.CHESS_LANG === "en") {
    lang = window.CHESS_LANG;
  } else {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "it") lang = saved;
  }
} catch {
  lang = "en";
}

export function getLang() {
  return lang;
}

export function t(key, vars = {}) {
  let text = dict[lang]?.[key] ?? dict.en[key] ?? dict.it[key] ?? String(key ?? "");
  Object.entries(vars).forEach(([name, value]) => {
    text = String(text).split(`{${name}}`).join(String(value));
  });
  return text;
}

export function setLang(next) {
  lang = next === "en" ? "en" : "it";
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang;
  return lang;
}

export function applyStaticI18n() {
  document.title = t("meta.title");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    el.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  document.querySelectorAll("[data-lang]").forEach((el) => {
    el.classList.toggle("is-on", el.getAttribute("data-lang") === lang);
  });
}

setLang(lang);
